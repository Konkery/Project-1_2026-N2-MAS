// ---------------------------------------------------------------------------------------------
// Функция валидации 'fvCheckFloatRange'
// Проверяет, является ли значение числом с плавающей точкой и входит ли в заданный диапазон.
//
// Важное замечание: регламенты компании требуют хранить числа с плавающей точкой только
// как ЧИСЛО (в нотации Excel), в отличие от целых чисел, которые как правило хранятся 
// как текст, но могут хранится и как число.
//
// Функция поддерживает два режима проверки данных: "мягкий" и "жесткий".
// При включенном "жестком" режиме пустые ячейки признаются НЕВАЛИДНЫМИ.
//
// аргументы:
// _selectTableName as text              - текстовое имя таблицы
// _columnName as text                   - имя столбца для проверки
// _minValue as number                   - минимальное значение диапазона
// _maxValue as number                   - максимальное значение диапазона
// optional _verificationMode as logical - режим валидации (true/null = жесткий, false = мягкий)
//
// возвращаемое значение:
// list                                  - список с кодами ошибок (0 или номер строки)
//
// ВАЖНО: 
// данная функция предназначена только (!) для создания и использования в автономном режиме,
// и не предназначена для вызова из другого query.
// ---------------------------------------------------------------------------------------------
(
    _selectTableName as text,
    _columnName as text,
    _minValue as number,
    _maxValue as number,
    optional _verificationMode as logical
) as list =>
let
    // Получаем доступ ко всем модульным функциям
    UF = QueryUtilsFunction,

    // Вызываем модульную версию функции, передавая ей все аргументы
    result = UF[fvCheckFloatRange](
        _selectTableName, 
        _columnName, 
        _minValue, 
        _maxValue, 
        _verificationMode
    )
in
    result